    // --- Core Display & Navigation Logic ---
    private void updateDisplay() {
        if (activeStudents == null || activeStudents.isEmpty()) {
            clearPanels();
            setResultsLog("<b>No records available.</b>");
            return;
        }

        if (currentStudentIndex < 0) currentStudentIndex = 0;
        if (currentStudentIndex >= activeStudents.size()) currentStudentIndex = activeStudents.size() - 1;

        Student s = activeStudents.get(currentStudentIndex);

        // Populate Student Fields
        tfStudentId.setText(s.getStudentId());
        tfStudentName.setText(s.getName());
        tfCourse.setText(s.getCourseOfStudy());

        // Populate Company Fields
        Company c = s.getAssignedCompany();
        tfCompany.setText(c != null ? c.getCompanyName() : "Unassigned");
        tfContactPerson.setText(c != null ? c.getContactPerson() : "N/A");
        tfRole.setText(s.getInternshipRole());
        tfAllowance.setText("$" + String.format("%.2f", s.getMonthlyAllowance()) + " / mth");

        // Ratings Logic
        ArrayList<Student.PerformanceRating> ratings = s.getRatings();
        if (ratings.isEmpty()) {
            tfWeeks.setText("N/A");
            tfMarks.setText("N/A");
            tfGradePoint.setText("N/A");
            lblRatingCounter.setText("Rating 0 of 0");
            btnPrevRating.setEnabled(false);
            btnNextRating.setEnabled(false);
        } else {
            if (currentRatingIndex < 0) currentRatingIndex = 0;
            if (currentRatingIndex >= ratings.size()) currentRatingIndex = ratings.size() - 1;

            Student.PerformanceRating r = ratings.get(currentRatingIndex);
            tfWeeks.setText(r.getWeeks() + " week(s)");
            tfMarks.setText(String.format("%.1f%%", r.getMarks()));
            tfGradePoint.setText(r.getGradePoint() + " / 4");

            lblRatingCounter.setText("Rating " + (currentRatingIndex + 1) + " of " + ratings.size());
            btnPrevRating.setEnabled(currentRatingIndex > 0);
            btnNextRating.setEnabled(currentRatingIndex < ratings.size() - 1);
        }

        // Grade Badges & Progress Bar
        double score = s.calculateOverallScore();
        tfOverallScore.setText(String.format("%.2f", score) + " / 4.00");

        int progress = (int) Math.round(score * 100);
        pbOverallScore.setValue(progress);
        pbOverallScore.setString(String.format("%.0f%%", (score / 4.0) * 100));

        if (score >= 3.50) {
            lblGradeBadge.setText(" DISTINCTION ");
            lblGradeBadge.setBackground(new Color(16, 185, 129)); // Emerald Green
            lblGradeBadge.setForeground(Color.WHITE);
            pbOverallScore.setForeground(new Color(16, 185, 129));
        } else if (score >= 3.00) {
            lblGradeBadge.setText(" CREDIT ");
            lblGradeBadge.setBackground(new Color(59, 130, 246)); // Sky Blue
            lblGradeBadge.setForeground(Color.WHITE);
            pbOverallScore.setForeground(new Color(59, 130, 246));
        } else if (score >= 2.00) {
            lblGradeBadge.setText(" PASS ");
            lblGradeBadge.setBackground(new Color(245, 158, 11)); // Amber
            lblGradeBadge.setForeground(Color.WHITE);
            pbOverallScore.setForeground(new Color(245, 158, 11));
        } else {
            lblGradeBadge.setText(" AT RISK ");
            lblGradeBadge.setBackground(new Color(239, 68, 68)); // Crimson
            lblGradeBadge.setForeground(Color.WHITE);
            pbOverallScore.setForeground(new Color(239, 68, 68));
        }

        // Student Nav Controls
        lblStudentCounter.setText("Student " + (currentStudentIndex + 1) + " of " + activeStudents.size());
        btnPrevStudent.setEnabled(currentStudentIndex > 0);
        btnNextStudent.setEnabled(currentStudentIndex < activeStudents.size() - 1);
    }

