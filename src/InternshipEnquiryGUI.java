    // Theme Switcher Engine
    private void toggleTheme() {
        isDarkMode = !isDarkMode;
        btnThemeToggle.setText(isDarkMode ? "Light Mode" : "Dark Mode");

        Color bgMain = isDarkMode ? new Color(15, 23, 42) : new Color(248, 250, 252);
        Color bgCard = isDarkMode ? new Color(30, 41, 59) : new Color(255, 255, 255);
        Color bgInput = isDarkMode ? new Color(51, 65, 85) : new Color(241, 245, 249);
        Color fgText = isDarkMode ? new Color(248, 250, 252) : new Color(30, 41, 59);
        Color borderColor = isDarkMode ? new Color(71, 85, 105) : new Color(203, 213, 225);

        getContentPane().setBackground(bgMain);
        centerPanel.setBackground(bgMain);
        leftColumn.setBackground(bgMain);
        rightColumn.setBackground(bgMain);

        updatePanelTheme(studentPanel, bgCard, fgText, borderColor);
        updatePanelTheme(companyPanel, bgCard, fgText, borderColor);
        updatePanelTheme(ratingsPanel, bgCard, fgText, new Color(37, 99, 235));
        updatePanelTheme(searchControlsPanel, bgCard, fgText, borderColor);
        updatePanelTheme(resultsPanel, bgCard, fgText, borderColor);

        for (JTextField tf : new JTextField[]{tfStudentId, tfStudentName, tfCourse, tfCompany, tfContactPerson, tfRole, tfAllowance, tfWeeks, tfMarks, tfGradePoint, tfOverallScore}) {
            if (tf != null) {
                tf.setBackground(bgInput);
                tf.setForeground(fgText);
            }
        }

        for (JTextField tf : new JTextField[]{tfSearchName, tfSearchCompany, tfSearchId}) {
            if (tf != null) {
                tf.setBackground(isDarkMode ? new Color(30, 41, 59) : Color.WHITE);
                tf.setForeground(fgText);
                tf.setCaretColor(fgText);
            }
        }

        bottomBar.setBackground(isDarkMode ? new Color(30, 41, 59) : new Color(241, 245, 249));

        if (activeStudents != null && !activeStudents.isEmpty()) {
            updateDisplay();
        }
    }

    private void updatePanelTheme(JPanel panel, Color bg, Color fg, Color border) {
        if (panel == null) return;
        panel.setBackground(bg);
        if (panel.getBorder() instanceof TitledBorder) {
            TitledBorder tb = (TitledBorder) panel.getBorder();
            tb.setTitleColor(fg);
            tb.setBorder(BorderFactory.createLineBorder(border));
        }
        for (Component c : panel.getComponents()) {
            if (c instanceof JLabel) {
                c.setForeground(fg);
            } else if (c instanceof JPanel) {
                updatePanelTheme((JPanel) c, bg, fg, border);
            }
        }
    }

