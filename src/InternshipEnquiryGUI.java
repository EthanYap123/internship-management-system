    // --- Search Features ---
    private void performSearchName() {
        String query = tfSearchName.getText().trim();
        if (query.isEmpty()) {
            clearPanels();
            setResultsLog("<h4 style='color: #dc2626; margin: 0;'>Input Required</h4>"
                    + "<p style='margin-top: 4px;'>Please enter a student name to search.</p>");
            return;
        }

        Student matchedStudent = null;
        int matchIdx = -1;
        for (int i = 0; i < manager.getStudents().size(); i++) {
            Student s = manager.getStudents().get(i);
            if (s.getName().equalsIgnoreCase(query)) {
                matchedStudent = s;
                matchIdx = i;
                break;
            }
        }

        if (matchedStudent != null) {
            this.activeStudents = new ArrayList<>(manager.getStudents());
            this.currentStudentIndex = matchIdx;
            this.currentRatingIndex = 0;
            updateDisplay();

            setResultsLog("<b>Search Result:</b> Found student <b>" + matchedStudent.getName() + "</b> (" + matchedStudent.getStudentId() + ")");
        } else {
            clearPanels();
            setResultsLog("<h4 style='color: #dc2626; margin: 0;'>No such student found</h4>"
                    + "<p style='margin-top: 4px;'>No record matches the name <i>\"" + query + "\"</i>.</p>");
        }
    }

    private void performSearchCompany() {
        String query = tfSearchCompany.getText().trim();
        if (query.isEmpty()) {
            clearPanels();
            setResultsLog("<h4 style='color: #dc2626; margin: 0;'>Input Required</h4>"
                    + "<p style='margin-top: 4px;'>Please enter a company name to search.</p>");
            return;
        }

        ArrayList<Student> companyStudents = new ArrayList<>();
        double totalScoreSum = 0;

        for (Student s : manager.getStudents()) {
            if (s.getAssignedCompany() != null && s.getAssignedCompany().getCompanyName().equalsIgnoreCase(query)) {
                companyStudents.add(s);
                totalScoreSum += s.calculateOverallScore();
            }
        }

        if (!companyStudents.isEmpty()) {
            double avgScore = totalScoreSum / companyStudents.size();

            this.activeStudents = companyStudents;
            this.currentStudentIndex = 0;
            this.currentRatingIndex = 0;
            updateDisplay();

            StringBuilder sb = new StringBuilder();
            sb.append("<h4 style='color: #1e3a8a; margin: 0 0 5px 0;'>Company Summary</h4>")
                    .append("<div><b>Company:</b> ").append(query).append("</div>")
                    .append("<div><b>Number of student(s) placed:</b> ").append(companyStudents.size()).append("</div>")
                    .append("<div><b>Average Internship Score:</b> ").append(String.format("%.2f", avgScore)).append(" / 4.00</div>")
                    .append("<hr style='border: 0; border-top: 1px solid #cbd5e1; margin: 8px 0;'>")
                    .append("<div><b>Assigned Students:</b></div><ul style='margin: 4px 0 0 15px; padding: 0;'>");

            for (Student s : companyStudents) {
                sb.append("<li><b>").append(s.getName()).append("</b> (").append(s.getStudentId()).append(") - ").append(s.getInternshipRole()).append("</li>");
            }
            sb.append("</ul>");

            setResultsLog(sb.toString());
        } else {
            clearPanels();
            setResultsLog("<h4 style='color: #dc2626; margin: 0;'>Company not found</h4>"
                    + "<p style='margin-top: 4px;'>No students are currently placed at <i>\"" + query + "\"</i>.</p>");
        }
    }

    private void performSearchId() {
        String query = tfSearchId.getText().trim().toUpperCase();
        if (query.isEmpty()) {
            clearPanels();
            setResultsLog("<h4 style='color: #dc2626; margin: 0;'>Input Required</h4>"
                    + "<p style='margin-top: 4px;'>Please enter a Student ID to search.</p>");
            return;
        }

        if (!query.matches("^S\\d{7}[A-Z]?$")) {
            clearPanels();
            setResultsLog("<h4 style='color: #dc2626; margin: 0;'>Format Error</h4>"
                    + "<p style='margin-top: 4px;'>Invalid format! Student ID should follow format e.g. S1234567A or S2312333.</p>");
            return;
        }

        Student matchedStudent = null;
        int matchIdx = -1;
        for (int i = 0; i < manager.getStudents().size(); i++) {
            Student s = manager.getStudents().get(i);
            if (s.getStudentId().equalsIgnoreCase(query)) {
                matchedStudent = s;
                matchIdx = i;
                break;
            }
        }

        if (matchedStudent != null) {
            this.activeStudents = new ArrayList<>(manager.getStudents());
            this.currentStudentIndex = matchIdx;
            this.currentRatingIndex = 0;
            updateDisplay();

            setResultsLog("<b>Search Result:</b> Found Student ID <b>" + matchedStudent.getStudentId() + "</b> (" + matchedStudent.getName() + ")");
        } else {
            clearPanels();
            setResultsLog("<h4 style='color: #dc2626; margin: 0;'>Student ID not found</h4>"
                    + "<p style='margin-top: 4px;'>No record matches Student ID <i>\"" + query + "\"</i>.</p>");
        }
    }

